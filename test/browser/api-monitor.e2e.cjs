const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');

(async () => {
  const root = path.resolve(__dirname, '../..');
  const tempRoot = process.env.TEST_TMP_DIR || require('node:os').tmpdir();
  await fs.mkdir(tempRoot, { recursive: true });
  const temp = await fs.mkdtemp(path.join(tempRoot, 'api-monitor-'));
  const screenshots = process.env.UI_SCREENSHOT_DIR || path.join(temp, 'screenshots');
  await fs.mkdir(screenshots, { recursive: true });
  process.env.TEMP = temp;
  process.env.TMP = temp;
  process.env.DATA_DIR = path.join(temp, 'data');
  process.env.PUBLIC_DIR = path.join(temp, 'public');
  await fs.cp(path.join(root, 'public'), process.env.PUBLIC_DIR, { recursive: true, filter: source => !source.startsWith(path.join(root, 'public/img') + path.sep) });
  const { app, initialize } = require(path.join(root, 'src/app'));
  await initialize();
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  let browser;
  let checks = 0;
  const check = (result, label) => { assert.ok(result, label); checks++; };
  try {
    browser = await chromium.launch({ headless: true });
    const page = await browser.newPage({ viewport: { width: 1280, height: 920 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`http://127.0.0.1:${server.address().port}`);
    await page.waitForFunction(() => document.querySelectorAll('.api-log-status.is-success').length === 2);
    check(!await page.locator('#api-monitor').evaluate(element => element.open), 'panel cerrado por defecto');
    check(await page.locator('#api-monitor-count').textContent() === '2', 'dos GET iniciales reales');
    await page.locator('#api-monitor>summary').focus();
    await page.keyboard.press('Enter');
    check(await page.locator('#api-monitor').evaluate(element => element.open), 'panel accesible con teclado');
    const form = page.locator('#record-form');
    await page.locator('#add-record').click();
    await form.locator('[name=especie]').fill('gato');
    await form.locator('[name=color]').fill('Gris');
    await form.locator('[name=edad]').fill('2');
    await form.locator('[name=sexo]').selectOption('hembra');
    const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aL1sAAAAASUVORK5CYII=', 'base64');
    await form.locator('[name=img]').setInputFiles({ name: 'foto-prueba.png', mimeType: 'image/png', buffer: png });
    await page.locator('#save-record').click();
    await page.locator('#record-dialog').waitFor({ state: 'hidden' });
    let latest = page.locator('.api-log-entry').first();
    check(await latest.locator('.api-log-method').textContent() === 'POST' && await latest.locator('.api-log-status').textContent() === '201', 'POST multipart y 201');
    check((await latest.textContent()).includes('foto-prueba.png') && !(await latest.textContent()).includes('base64'), 'solo metadatos del archivo');
    await page.getByRole('button', { name: 'Editar gato', exact: true }).click();
    await form.locator('[name=color]').fill('Blanco');
    await page.locator('#save-record').click();
    await page.locator('#record-dialog').waitFor({ state: 'hidden' });
    latest = page.locator('.api-log-entry').first();
    check(await latest.locator('.api-log-method').textContent() === 'PUT' && await latest.locator('.api-log-status').textContent() === '200', 'PUT real y 200');
    check((await latest.locator('pre').last().textContent()).includes('Blanco'), 'respuesta real de actualización');
    await page.getByRole('button', { name: 'Eliminar gato', exact: true }).click();
    await page.locator('#confirm-delete').click();
    await page.locator('#delete-dialog').waitFor({ state: 'hidden' });
    latest = page.locator('.api-log-entry').first();
    check(await latest.locator('.api-log-method').textContent() === 'DELETE' && await latest.locator('.api-log-status').textContent() === '200', 'DELETE real y 200');
    await page.locator('[data-resource=users]').click();
    await page.locator('#add-record').click();
    await form.locator('[name=firstname]').fill('Ana');
    await form.locator('[name=lastname]').fill('Prueba');
    await form.locator('[name=username]').fill('ana.monitor');
    await form.locator('[name=password]').fill('clave-privada-monitor');
    await page.locator('#save-record').click();
    await page.locator('#record-dialog').waitFor({ state: 'hidden' });
    check(!(await page.locator('#api-monitor').textContent()).includes('clave-privada-monitor'), 'contraseña multipart oculta');
    check((await page.locator('.api-log-entry').first().textContent()).includes('[oculto]'), 'redacción visible de la contraseña');
    await page.evaluate(async () => {
      try { await api('/api/users', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ firstname: 'Ana', lastname: 'Prueba', username: 'ana.monitor', password: 'clave-json-privada' }) }); } catch {}
    });
    latest = page.locator('.api-log-entry').first();
    check(await latest.locator('.api-log-status').textContent() === '400', 'respuesta de validación 400');
    check(!(await latest.textContent()).includes('clave-json-privada') && (await latest.textContent()).includes('[oculto]'), 'contraseña JSON oculta');
    await page.evaluate(async () => { try { await api('/api/pets/999999'); } catch {} });
    check(await page.locator('.api-log-entry').first().locator('.api-log-status').textContent() === '404', 'respuesta 404');
    await page.locator('.api-log-entry').first().locator('summary').click();
    check((await page.locator('.api-log-entry').first().locator('pre').last().textContent()).includes('Recurso no encontrado'), 'error JSON consultable');
    await page.locator('#toast').waitFor({ state: 'hidden' });
    await page.mouse.move(5, 5);
    await page.screenshot({ path: path.join(screenshots, 'panel-abierto.png'), fullPage: true });
    await page.route('**/api/monitor-fixture', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ password: 'respuesta-privada', nested: { access_token: 'token-privado' }, dato: '<img src=x onerror="window.__injected=true">' }) }));
    await page.evaluate(async () => { await api('/api/monitor-fixture'); });
    latest = page.locator('.api-log-entry').first();
    check(!(await latest.textContent()).includes('respuesta-privada') && !(await latest.textContent()).includes('token-privado'), 'credenciales anidadas de respuesta ocultas');
    check(await latest.locator('img').count() === 0 && !await page.evaluate(() => window.__injected), 'respuestas mostradas como texto sin ejecutar HTML');
    await page.evaluate(async () => { await api('/api/pets?token=consulta-privada'); });
    check(!(await page.locator('.api-log-entry').first().textContent()).includes('consulta-privada'), 'credenciales en URL ocultas');
    await page.route('**/api/pets?network-test=1', route => route.abort());
    await page.evaluate(async () => { try { await api('/api/pets?network-test=1'); } catch {} });
    check(await page.locator('.api-log-entry').first().locator('.api-log-status').textContent() === 'Sin conexión', 'fallo de red registrado');
    await page.route('**/api/pets?bad-json=1', route => route.fulfill({ status: 200, contentType: 'text/plain', body: 'contenido no JSON' }));
    await page.evaluate(async () => { try { await api('/api/pets?bad-json=1'); } catch {} });
    check((await page.locator('.api-log-entry').first().textContent()).includes('no devolvió una respuesta JSON válida'), 'respuesta no JSON registrada');
    let pendingRoute;
    await page.route('**/api/pets?slow=1', route => { pendingRoute = route; });
    await page.evaluate(() => { window.__pendingMonitor = api('/api/pets?slow=1'); });
    await page.waitForFunction(() => document.querySelector('.api-log-entry .api-log-status').textContent === 'En curso');
    check(await page.locator('.api-log-entry').first().locator('.api-log-status').textContent() === 'En curso', 'estado pendiente visible');
    await page.locator('#api-monitor-clear').click();
    check(await page.locator('#api-monitor-count').textContent() === '0' && await page.locator('#api-monitor-empty').isVisible(), 'limpieza del historial');
    await pendingRoute.fulfill({ status: 200, contentType: 'application/json', body: '[]' });
    await page.evaluate(() => window.__pendingMonitor);
    check(await page.locator('.api-log-entry').count() === 0, 'petición pendiente descartada al limpiar');
    await page.evaluate(async () => { await Promise.all(Array.from({ length: 44 }, () => api('/api/pets'))); });
    check(await page.locator('.api-log-entry').count() === 40 && await page.locator('#api-monitor-count').textContent() === '40', 'límite de 40 peticiones');
    await page.locator('.api-log-entry').first().locator('summary').click();
    await page.evaluate(async () => { window.__expandedMonitor = document.querySelector('.api-log-entry'); await api('/api/pets'); });
    check(await page.evaluate(() => window.__expandedMonitor.isConnected && window.__expandedMonitor.open), 'filas abiertas conservadas al recibir peticiones');
    for (const width of [320, 390, 768]) {
      await page.setViewportSize({ width, height: 900 });
      await page.waitForFunction(() => document.getAnimations().every(animation => animation.playState === 'finished'));
      await page.evaluate(async () => { await api('/api/pets?descripcion=' + 'x'.repeat(200)); });
      check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `panel sin desbordamiento a ${width}px`);
    }
    await page.locator('#api-monitor>summary').click();
    check(!await page.locator('#api-monitor').evaluate(element => element.open), 'panel vuelve a ocultarse');
    await page.reload();
    await page.waitForFunction(() => document.querySelectorAll('.api-log-status.is-success').length === 2);
    check(await page.locator('.api-log-entry').count() === 2 && !await page.locator('#api-monitor').evaluate(element => element.open), 'sin persistencia y cerrado al recargar');
    check(errors.length === 0, `sin errores JavaScript: ${errors.join('; ')}`);
    console.log(`${checks} comprobaciones del panel de API superadas en Chromium.`);
  } finally {
    if (browser) await browser.close();
    await new Promise(resolve => server.close(resolve));
    await fs.rm(temp, { recursive: true, force: true });
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
